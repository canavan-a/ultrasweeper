// Notifee channel setup shared by police alerts (alerts.ts) and the
// background-scan service (background.ts).
//
// Android fixes a channel's sound and vibration when the channel is created;
// the app can't change them later. So each sound/vibration combination from
// Settings gets its own alert channel, and alerts post to the one matching
// the current settings. (The user can still override any of them in
// Android's per-channel notification settings.)
import notifee, {AndroidImportance, AndroidVisibility, AuthorizationStatus} from '@notifee/react-native';

export const CH_SCANNING = 'scanning';
export const NID_SCANNING = 'scanning';

// res/raw/police_ping.wav, generated by tools/gen-alert-sound.mjs.
const PING_SOUND = 'police_ping';
// Wait/buzz pairs in ms, in the chime's three-beat rhythm (one ping per
// 200 ms). Notifee needs an even count of positive values.
export const PING_VIBRATION = [1, 110, 90, 110, 90, 110];

export function alertChannelId(sound: boolean, vibrate: boolean): string {
  return `police-alert${sound ? '-sound' : ''}${vibrate ? '-vibrate' : ''}`;
}

// Tap target for every notification. Not Notifee's default launch activity:
// that resolves to whichever launcher alias is enabled (.IconLight, …, see
// AndroidManifest.xml), which isn't a class Notifee can start. Same fix as
// super-badger's channels.ts.
export const PRESS_ACTION = {id: 'default', launchActivity: 'com.ultrascannerapp.MainActivity'};

export const SMALL_ICON = 'ic_stat_scanner';

let ensured: Promise<void> | null = null;

// One createChannels() call, not one per channel: every native call queues
// behind the scanner's serial events on a busy JS thread, so sequential
// calls added up to a visible delay before the first alert. App.tsx also
// calls this at startup so an alert never waits on it.
export function ensureChannels(): Promise<void> {
  if (!ensured) {
    const channels: Parameters<typeof notifee.createChannels>[0] = [
      {
        id: CH_SCANNING,
        name: 'Background scanning',
        description: 'Shown while the scanner keeps listening with the app in the background.',
        importance: AndroidImportance.LOW,
      },
    ];
    for (const sound of [true, false]) {
      for (const vibrate of [true, false]) {
        const what = [sound && 'chime', vibrate && 'vibration'].filter(Boolean).join(' + ') || 'silent';
        channels.push({
          id: alertChannelId(sound, vibrate),
          name: `Police alerts (${what})`,
          description: 'A police device was heard nearby.',
          importance: AndroidImportance.HIGH,
          visibility: AndroidVisibility.PUBLIC,
          sound: sound ? PING_SOUND : undefined,
          vibration: vibrate,
          vibrationPattern: vibrate ? PING_VIBRATION : undefined,
        });
      }
    }
    ensured = notifee.createChannels(channels).catch(err => {
      ensured = null; // retry next time
      throw err;
    });
  }
  return ensured;
}

/** Ask for POST_NOTIFICATIONS (Android 13+); resolves true when allowed. */
export async function requestNotificationPermission(): Promise<boolean> {
  const res = await notifee.requestPermission();
  return res.authorizationStatus >= AuthorizationStatus.AUTHORIZED;
}
