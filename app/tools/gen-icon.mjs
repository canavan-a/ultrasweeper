#!/usr/bin/env node
// Generates the launcher icons: a radar sweep (rings, crosshair, fading sweep
// wedge, a few contact blips), one colorway per app theme.
//
// Writes, under android/app/src/main/res:
//   drawable/ic_launcher_fg_<theme>.xml   adaptive-icon foreground (API 26+)
//   drawable/ic_launcher_mono.xml         Android 13+ themed-icon layer
//   mipmap-*dpi/ic_launcher_<theme>{,_round}.png   legacy (< API 26) icons
// The adaptive-icon wrappers and ic_bg_* colors are left as they are.
//
// PNG rendering needs ImageMagick with an SVG delegate (`magick`) on PATH.
//
//   node tools/gen-icon.mjs

import {execFileSync} from 'node:child_process';
import {mkdtempSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const RES = join(dirname(fileURLToPath(import.meta.url)), '..', 'android/app/src/main/res');

// bg matches values/ic_theme_icons.xml; ring = theme textMuted; accent is the
// theme primary, brightened where the primary is too dim against its bg.
const THEMES = {
  light: {bg: '#ffffff', ring: '#57606a', accent: '#0969da', blip: '#0969da'},
  dark: {bg: '#0d1117', ring: '#8b949e', accent: '#2f81f7', blip: '#a5d6ff'},
  slate: {bg: '#1e2530', ring: '#93a0b3', accent: '#5aa9e6', blip: '#c6e4fb'},
  sepia: {bg: '#f4ecd8', ring: '#7a6a4d', accent: '#a0651b', blip: '#a0651b'},
  ember: {bg: '#050403', ring: '#8a6c5f', accent: '#d4582f', blip: '#ffb38a'},
};

// Geometry in the 108x108 adaptive-icon viewport; everything stays inside the
// 66dp safe zone (radius 33 around the center).
const C = 54;
const R_OUTER = 28;
const RINGS = [19, 10];
const LEAD = -40; // degrees, screen coords (0 = +x, clockwise positive)
const WEDGE = [
  // [from lead, to lead, alpha]: stacked slices fake a fading trail.
  [0, 18, 0.5],
  [18, 38, 0.3],
  [38, 62, 0.15],
];
const BLIPS = [
  // [angle, radius, size, alpha]
  [-55, 20, 2.6, 1],
  [150, 14, 2.0, 0.55],
  [60, 23, 1.6, 0.35],
];

const f = n => +n.toFixed(4);
const pt = (deg, r) => {
  const a = (deg * Math.PI) / 180;
  return [f(C + r * Math.cos(a)), f(C + r * Math.sin(a))];
};
const circle = (cx, cy, r) =>
  `M${f(cx - r)},${f(cy)}a${f(r)},${f(r)} 0 1,0 ${f(2 * r)},0a${f(r)},${f(r)} 0 1,0 ${f(-2 * r)},0z`;
const wedge = (a0, a1, r) => {
  const [x0, y0] = pt(LEAD - a0, r);
  const [x1, y1] = pt(LEAD - a1, r);
  return `M${C},${C}L${x0},${y0}A${r},${r} 0 0,0 ${x1},${y1}z`;
};

// Shapes as {d, fill?|stroke?, width?, alpha, role}; role picks the color.
function shapes() {
  const s = [];
  const rIn = R_OUTER - 1.2;
  for (const [a0, a1, alpha] of WEDGE) s.push({d: wedge(a0, a1, rIn), fill: 'accent', alpha});
  s.push({d: circle(C, C, R_OUTER), stroke: 'ring', width: 2.4, alpha: 1});
  for (const r of RINGS) s.push({d: circle(C, C, r), stroke: 'ring', width: 1.2, alpha: 0.6});
  s.push({
    d: `M${C - R_OUTER},${C}H${C + R_OUTER}M${C},${C - R_OUTER}V${C + R_OUTER}`,
    stroke: 'ring',
    width: 0.9,
    alpha: 0.4,
  });
  const [lx, ly] = pt(LEAD, rIn);
  s.push({d: `M${C},${C}L${lx},${ly}`, stroke: 'accent', width: 2, alpha: 1, cap: 'round'});
  for (const [a, r, size, alpha] of BLIPS) {
    const [x, y] = pt(a, r);
    s.push({d: circle(x, y, size), fill: 'blip', alpha});
  }
  s.push({d: circle(C, C, 2.2), fill: 'accent', alpha: 1});
  return s;
}

function vectorXml(colorOf, comment) {
  const paths = shapes()
    .map(sh => {
      const c = colorOf(sh.fill ?? sh.stroke);
      const attrs = sh.fill
        ? [`android:fillColor="${c}"`, sh.alpha !== 1 && `android:fillAlpha="${sh.alpha}"`]
        : [
            `android:strokeColor="${c}"`,
            `android:strokeWidth="${sh.width}"`,
            sh.alpha !== 1 && `android:strokeAlpha="${sh.alpha}"`,
            sh.cap && `android:strokeLineCap="${sh.cap}"`,
          ];
      return `    <path\n        ${attrs.filter(Boolean).join('\n        ')}\n        android:pathData="${sh.d}" />`;
    })
    .join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen-icon.mjs: ${comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${paths}
</vector>
`;
}

// Legacy icon: the adaptive icon's visible 72x72 center on a shaped background.
function legacySvg(theme, round) {
  const t = THEMES[theme];
  const bg = round
    ? `<circle cx="54" cy="54" r="36" fill="${t.bg}"/>`
    : `<rect x="20" y="20" width="68" height="68" rx="14" fill="${t.bg}"/>`;
  const body = shapes()
    .map(sh => {
      const c = t[sh.fill ?? sh.stroke];
      return sh.fill
        ? `<path d="${sh.d}" fill="${c}" fill-opacity="${sh.alpha}"/>`
        : `<path d="${sh.d}" fill="none" stroke="${c}" stroke-width="${sh.width}" stroke-opacity="${sh.alpha}"${sh.cap ? ` stroke-linecap="${sh.cap}"` : ''}/>`;
    })
    .join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">${bg}${body}</svg>`;
}

const DENSITIES = {mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192};

const tmp = mkdtempSync(join(tmpdir(), 'gen-icon-'));
try {
  for (const theme of Object.keys(THEMES)) {
    writeFileSync(
      join(RES, `drawable/ic_launcher_fg_${theme}.xml`),
      vectorXml(role => THEMES[theme][role], `radar sweep, ${theme} theme.`),
    );
    for (const round of [false, true]) {
      const svg = join(tmp, `${theme}${round ? '_round' : ''}.svg`);
      writeFileSync(svg, legacySvg(theme, round));
      for (const [dpi, px] of Object.entries(DENSITIES)) {
        const out = join(RES, `mipmap-${dpi}/ic_launcher_${theme}${round ? '_round' : ''}.png`);
        execFileSync('magick', [
          '-background', 'none', '-density', String((96 * px) / 72), svg,
          '-resize', `${px}x${px}`, '-strip', `PNG32:${out}`,
        ]);
      }
    }
  }
  writeFileSync(
    join(RES, 'drawable/ic_launcher_mono.xml'),
    vectorXml(() => '#FFFFFF', 'single-color radar sweep for Android 13+ themed icons.'),
  );
} finally {
  rmSync(tmp, {recursive: true, force: true});
}
console.log('icons written to', RES);
